// 고양이 오목 개인정보처리방침 정적 페이지 생성기. 런타임 JS·원격 폰트·추적 없음.
// 원문: tools/privacy-cat-gomoku/<lang>.json  →  games/cat-gomoku/privacy/[<path>/]index.html
// 사용: node tools/build-cat-gomoku-privacy.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { policyStyle } from './policy-style.mjs';
import { applyPolicyNotice } from './policy-notice.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// 공개 방침 8개 언어. 앱의 방침 링크는 한국어 기본 주소이며 페이지 안에서 언어를 선택한다.
const languages = {
  ko: '한국어',
  en: 'English',
  ja: '日本語',
  es: 'Español',
  'pt-BR': 'Português (Brasil)',
  'zh-TW': '中文（繁體）',
  de: 'Deutsch',
  fr: 'Français',
};
const ids = ['scope', 'local', 'play-games', 'online', 'ads', 'choices', 'reports', 'providers', 'delete-data', 'rights', 'young-users', 'updates'];
const base = '/games/cat-gomoku/privacy/';
const origin = 'https://sjw0408.github.io';
const route = code => code === 'ko' ? base : `${base}${code.toLowerCase()}/`;
const esc = text => String(text).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));
const paragraph = list => (list ?? []).map(text => `      <p>${esc(text)}</p>`).join('\n');
const list = items => items?.length ? `      <ul>\n${items.map(text => `        <li>${esc(text)}</li>`).join('\n')}\n      </ul>` : '';
const forbidden = ['AdMob', 'UMP', '1.2.0', 'Yarn Tangle Cats', 'com.teamcp.yarntangle', '냥이 털실 풀기'];

let changed = 0;
for (const [code, nativeName] of Object.entries(languages)) {
  const raw = readFileSync(resolve(root, 'tools/privacy-cat-gomoku', `${code}.json`), 'utf8');
  for (const name of forbidden) assert.ok(!raw.includes(name), `${code}: forbidden name ${name}`);
  const data = JSON.parse(raw);
  assert.equal(data.language, code);
  for (const key of ['title', 'description', 'back', 'date', 'summary', 'contents', 'resources', 'contact']) {
    assert.equal(typeof data[key], 'string', `${code}: ${key}`);
    assert.ok(data[key].trim());
  }
  assert.deepEqual(data.sections.map(section => section.id), ids, `${code}: section drift`);
  assert.equal(data.links.length, 3);
  for (const section of data.sections) {
    assert.ok(section.title.trim());
    const text = [...(section.paragraphs ?? []), ...(section.items ?? []), ...(section.after ?? [])];
    assert.ok(text.length > 0);
    for (const value of text) assert.ok(typeof value === 'string' && value.trim(), `${code}: empty content`);
  }
  const resources = [
    'https://unity.com/legal/game-player-and-app-user-privacy-policy',
    `https://policies.google.com/privacy?hl=${code}`,
    'https://firebase.google.com/support/privacy',
  ];
  const baseHtml = `<!doctype html>
<!-- Generated by tools/build-cat-gomoku-privacy.mjs from tools/privacy-cat-gomoku/${code}.json. -->
<html lang="${code}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="light">
  <meta name="theme-color" content="#fff8ed">
  <meta name="description" content="${esc(data.description)}">
  <meta name="policy-revision" content="2026-11-20-v1">
  <title>${esc(data.title)}</title>
  <link rel="canonical" href="${origin}${route(code)}">
${Object.keys(languages).map(lang => `  <link rel="alternate" hreflang="${lang}" href="${origin}${route(lang)}">`).join('\n')}
  <link rel="alternate" hreflang="x-default" href="${origin}${route('en')}">
${policyStyle(root, base)}
</head>
<body>
  <main>
    <a class="back" href="/games/cat-gomoku/">← ${esc(data.back)}</a>
    <nav class="languages" aria-label="Language">
${Object.entries(languages).map(([lang, name]) => `      <a href="${route(lang)}" lang="${lang}" hreflang="${lang}"${lang === code ? ' aria-current="page"' : ''}>${esc(name)}</a>`).join('\n')}
    </nav>
    <h1>${esc(data.title)}</h1>
    <p class="effective">${esc(data.date)}</p>
    <p class="notice">${esc(data.summary)}</p>
    <nav class="contents" aria-label="${esc(data.contents)}">
      <h2>${esc(data.contents)}</h2>
      <ul>
${data.sections.map(section => `        <li><a href="#${section.id}">${esc(section.title)}</a></li>`).join('\n')}
      </ul>
    </nav>
${data.sections.map(section => `    <section aria-labelledby="${section.id}">
      <h2 id="${section.id}">${esc(section.title)}</h2>
${paragraph(section.paragraphs)}
${list(section.items)}
${paragraph(section.after)}
    </section>`).join('\n')}
    <section aria-labelledby="resources">
      <h2 id="resources">${esc(data.resources)}</h2>
      <ul>
${resources.map((href, i) => `        <li><a href="${href}">${esc(data.links[i])}</a></li>`).join('\n')}
      </ul>
    </section>
    <footer>
      <h2>${esc(data.contact)}</h2>
      <p><a href="mailto:teamcp.channel@gmail.com">teamcp.channel@gmail.com</a></p>
      <p>TeamCP · Cat Gomoku · com.teamcp.catgomoku</p>
      <p lang="${code}">${esc(nativeName)}</p>
    </footer>
  </main>
</body>
</html>
`;
  // 개인정보 보호법 추가 고지(국외 이전·권리·만 14세 미만·안전성·보호책임자): tools/policy-notice.json
  const html = applyPolicyNotice(baseHtml, 'cat-gomoku', code);
  assert.equal((html.match(/id="delete-data"/g) ?? []).length, 1, `${code}: #delete-data`);
  const target = resolve(root, `.${route(code)}`, 'index.html');
  let existing = null;
  try { existing = readFileSync(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing !== html) {
    changed++;
    if (process.argv.includes('--check')) console.error(`Out of date: ${route(code)}index.html`);
    else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, html, 'utf8');
    }
  }
}
if (process.argv.includes('--check') && changed) process.exitCode = 1;
else console.log(`Cat Gomoku privacy: ${Object.keys(languages).length} languages, ${changed} ${process.argv.includes('--check') ? 'out of date' : 'updated'}.`);
