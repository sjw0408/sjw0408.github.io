// Deterministic static document generator. No runtime JS, remote fonts or tracking.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const languages = { ko: '한국어', en: 'English', ja: '日本語', es: 'Español', fr: 'Français', de: 'Deutsch' };
const ids = ['scope', 'local', 'google', 'ads', 'choices', 'providers', 'delete-data', 'rights', 'young-users', 'updates'];
const base = '/games/cat-detective/privacy/';
const origin = 'https://sjw0408.github.io';
const route = code => code === 'ko' ? base : `${base}${code}/`;
const esc = text => String(text).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));
const paragraph = list => (list ?? []).map(text => `      <p>${esc(text)}</p>`).join('\n');
const list = items => items?.length ? `      <ul>\n${items.map(text => `        <li>${esc(text)}</li>`).join('\n')}\n      </ul>` : '';

let changed = 0;
for (const [code, nativeName] of Object.entries(languages)) {
  const data = JSON.parse(readFileSync(resolve(root, 'tools/privacy', `${code}.json`), 'utf8'));
  assert.equal(data.language, code);
  for (const key of ['title', 'description', 'back', 'date', 'version', 'summary', 'contents', 'resources', 'contact']) {
    assert.equal(typeof data[key], 'string', `${code}: ${key}`);
    assert.ok(data[key].trim());
  }
  assert.deepEqual(data.sections.map(section => section.id), ids, `${code}: section drift`);
  assert.equal(data.links.length, 4);
  for (const section of data.sections) {
    assert.ok(section.title.trim());
    const text = [...(section.paragraphs ?? []), ...(section.items ?? []), ...(section.after ?? [])];
    assert.ok(text.length > 0);
    for (const value of text) assert.ok(typeof value === 'string' && value.trim(), `${code}: empty content`);
  }
  const resources = [
    `https://policies.google.com/privacy?hl=${code}`,
    `https://support.google.com/googleplay/answer/9130646?hl=${code}`,
    'https://myaccount.google.com/',
    'https://unity.com/legal/game-player-and-app-user-privacy-policy',
  ];
  const html = `<!doctype html>
<!-- Generated by tools/build-cat-privacy.mjs from tools/privacy/${code}.json. -->
<html lang="${code}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="light">
  <meta name="theme-color" content="#eef9f4">
  <meta name="description" content="${esc(data.description)}">
  <meta name="policy-revision" content="2026-09-07-v3">
  <title>${esc(data.title)}</title>
  <link rel="canonical" href="${origin}${route(code)}">
${Object.keys(languages).map(lang => `  <link rel="alternate" hreflang="${lang}" href="${origin}${route(lang)}">`).join('\n')}
  <link rel="alternate" hreflang="x-default" href="${origin}${route('en')}">
  <link rel="stylesheet" href="${base}policy.css">
</head>
<body>
  <main>
    <a class="back" href="/games/cat-detective/">← ${esc(data.back)}</a>
    <nav class="languages" aria-label="Language">
${Object.entries(languages).map(([lang, name]) => `      <a href="${route(lang)}" lang="${lang}" hreflang="${lang}"${lang === code ? ' aria-current="page"' : ''}>${esc(name)}</a>`).join('\n')}
    </nav>
    <h1>${esc(data.title)}</h1>
    <p class="effective">${esc(data.date)}</p>
    <p class="notice">${esc(data.summary)}</p>
    <p class="version">${esc(data.version)}</p>
    <nav class="contents" aria-label="${esc(data.contents)}">
      <h2>${esc(data.contents)}</h2>
      <ul>
${data.sections.map(section => `        <li><a href="#${section.id}">${esc(section.title)}</a></li>`).join('\n')}
      </ul>
    </nav>
${data.sections.map(section => `    <section aria-labelledby="${section.id}">
      <h2 id="${section.id}">${esc(section.title)}</h2>
${paragraph(section.paragraphs)}
${list(section.items)}
${paragraph(section.after)}
    </section>`).join('\n')}
    <section aria-labelledby="resources">
      <h2 id="resources">${esc(data.resources)}</h2>
      <ul>
${resources.map((href, i) => `        <li><a href="${href}">${esc(data.links[i])}</a></li>`).join('\n')}
      </ul>
    </section>
    <footer>
      <h2>${esc(data.contact)}</h2>
      <p><a href="mailto:sjw0480@gmail.com">sjw0480@gmail.com</a></p>
      <p>TeamCP · Cat Detective · com.teamcp.catdetective</p>
      <p lang="${code}">${esc(nativeName)}</p>
    </footer>
  </main>
</body>
</html>
`;
  const target = resolve(root, `.${route(code)}`, 'index.html');
  let existing = null;
  try { existing = readFileSync(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing !== html) {
    changed++;
    if (process.argv.includes('--check')) console.error(`Out of date: ${route(code)}index.html`);
    else {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, html, 'utf8');
    }
  }
}
if (process.argv.includes('--check') && changed) process.exitCode = 1;
else console.log(`Privacy documents: 6 languages, ${changed} ${process.argv.includes('--check') ? 'out of date' : 'updated'}.`);
