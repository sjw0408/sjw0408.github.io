import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { escape, origin, shareTags } from './portal-head.mjs';
import { policyTouchStyles } from './policy-style.mjs';

const check = process.argv.includes('--check');

for (const [slug, korean, english, scheme, theme] of [
  ['slime-express', '슬라임 택배', 'Slime Express', 'light', '#fff8ed'],
  ['cat-rush3', '3분 냥냥 던전', 'Cat Dungeon: 3-Min Rush', 'dark', '#0d111d'],
]) {
  const source = new URL(`privacy-${slug}/`, import.meta.url);
  const css = readFileSync(new URL('style.css', source), 'utf8');
  const root = `/games/${slug}/privacy/`;

  for (const lang of ['ko', 'en']) {
    const isEnglish = lang === 'en';
    const path = root + (isEnglish ? 'en/' : '');
    const game = (isEnglish ? '/en' : '') + `/games/${slug}/`;
    const input = readFileSync(new URL(lang + '.html', source), 'utf8');
    const [, title, description, body] = input.match(/^<title>(.+)<\/title>\n<meta name="description" content="([^"]+)">\n([\s\S]+)$/);
    const html = `<!doctype html>
<!-- Generated by tools/build-store-privacy.mjs. -->
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="${scheme}">
  <meta name="theme-color" content="${theme}">
  <title>${escape(title)}</title>
  <meta name="description" content="${escape(description)}">
  <link rel="canonical" href="${origin}${path}">
  <link rel="alternate" hreflang="ko" href="${origin}${root}">
  <link rel="alternate" hreflang="en" href="${origin}${root}en/">
${shareTags(title, description, path, lang, '/games/' + slug + '/share.jpg')}
  <style>
${css}    ${policyTouchStyles}
    .languages { display: flex; flex-wrap: wrap; gap: 8px; margin: 10px 0; }
    .languages a { padding: 4px 12px; border: 1px solid currentColor; border-radius: 8px; }
    .languages [aria-current="page"] { font-weight: 800; }
    a:focus-visible { outline: 2px solid currentColor; outline-offset: 3px; }
    p, li, td, dd { overflow-wrap: anywhere; }
  </style>
</head>
<body>
  <main>
    <a class="back" href="${game}">← ${escape(isEnglish ? english + ' game information' : korean + ' 게임 정보')}</a>
    <nav class="languages" aria-label="${isEnglish ? 'Language' : '언어'}">
      <a href="${root}" lang="ko" hreflang="ko"${isEnglish ? '' : ' aria-current="page"'}>한국어</a>
      <a href="${root}en/" lang="en" hreflang="en"${isEnglish ? ' aria-current="page"' : ''}>English</a>
    </nav>
${body}  </main>
  <script>
    const fromStore = new URLSearchParams(location.search).get('from') === 'onestore';
    if (fromStore) document.querySelector('.back').href = '${game}onestore/';
    for (const link of document.querySelectorAll('.languages a')) {
      link.addEventListener('click', () => {
        link.search = fromStore ? '?from=onestore' : '';
        link.hash = location.hash;
      });
    }
  </script>
</body>
</html>
`;
    const output = new URL(`..${path}index.html`, import.meta.url);
    if (check) {
      if (readFileSync(output, 'utf8') !== html) {
        console.error('Out of date:', path);
        process.exitCode = 1;
      }
    } else {
      mkdirSync(dirname(fileURLToPath(output)), { recursive: true });
      writeFileSync(output, html);
    }
  }
}
