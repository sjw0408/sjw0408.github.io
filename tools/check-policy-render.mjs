// Check every published policy, including legacy pages without a generator.
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { policyStyle } from './policy-style.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const path = resolve(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}
const pages = [...walk(resolve(root, 'games')).filter(path => /[\\/]privacy[\\/].*index\.html$/.test(path)), resolve(root, 'privacy/index.html')];
let links = 0;
const otherMissingLinks = new Set();
for (const page of pages) {
  const html = readFileSync(page, 'utf8');
  const name = relative(root, page);
  assert.ok(!/<script\b|<iframe\b|<link\b[^>]*\brel=["']stylesheet|http-equiv=["']refresh/i.test(html), `${name}: runtime dependency or redirect`);
  const style = html.match(/<style>([\s\S]*?)<\/style>/i)?.[1];
  assert.ok(style && !/@import\b|url\s*\(/i.test(style), `${name}: missing or remote style`);
  const scheme = html.match(/name="color-scheme" content="([^"]+)"/)?.[1];
  assert.ok(scheme === 'light' || scheme === 'dark', `${name}: theme missing`);
  assert.ok(style.includes(`color-scheme: ${scheme === 'light' ? 'only light' : 'dark'};`), `${name}: CSS theme mismatch`);
  assert.ok(/<h1>[^<]+<\/h1>/.test(html), `${name}: missing title`);
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  assert.equal(ids.length, new Set(ids).size, `${name}: duplicate IDs`);
  if (html.includes('<!-- Generated by tools/')) {
    const slug = name.split(/[\\/]/)[1];
    const expected = policyStyle(root, `/games/${slug}/privacy/`);
    assert.ok(html.includes(expected), `${name}: stale generated CSS`);
    assert.ok(ids.includes('delete-data'), `${name}: missing deletion anchor`);
  }
  for (const [, href] of html.matchAll(/\bhref="([^"]+)"/g)) {
    if (href.startsWith('#')) assert.ok(ids.includes(href.slice(1)), `${name}: missing ${href}`);
    if (href.startsWith('/')) {
      const pathname = href.split('#')[0];
      const target = resolve(root, `.${pathname}`, pathname.endsWith('/') ? 'index.html' : '');
      if (pathname.includes('/privacy/')) assert.ok(existsSync(target), `${name}: broken policy link ${href}`);
      else if (!existsSync(target)) otherMissingLinks.add(href);
    }
    links++;
  }
}
console.log(`PASS: ${pages.length} policies, ${links} links, self-contained CSS, explicit themes and deletion anchors.`);
if (otherMissingLinks.size) console.log(`Existing non-policy destinations missing from source (unchanged): ${[...otherMissingLinks].join(', ')}`);

if (process.argv.includes('--live')) {
  // Limit concurrent requests and require the actual public URL, no redirects.
  for (let start = 0; start < pages.length; start += 4) {
    await Promise.all(pages.slice(start, start + 4).map(async page => {
      const path = '/' + relative(root, page).replaceAll('\\', '/').replace(/index\.html$/, '');
      const response = await fetch(`https://sjw0408.github.io${path}`, { signal: AbortSignal.timeout(20000), redirect: 'error' });
      assert.equal(response.status, 200, path);
      assert.equal((await response.text()).replaceAll('\r\n', '\n'), readFileSync(page, 'utf8').replaceAll('\r\n', '\n'), `${path}: published bytes differ`);
    }));
  }
  console.log(`PASS: ${pages.length} public policy URLs returned HTTP 200 and exact generated content (not a visual check).`);
}
